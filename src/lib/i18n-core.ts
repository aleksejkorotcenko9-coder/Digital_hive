export type Dict = Record<string, string>

export const BASE_DICTS: Record<Lang, Dict> = { ru: RU, en: EN, fr: FR, kk: KK, be: BE, zh: ZH }

/**
 * Дополнительные словари (по группам экранов) — подключаются из модулей
 * i18n-extra-*.ts, чтобы переводить ВСЁ: оставшиеся экраны, ответы агента
 * и содержательные тексты демо-данных. Отсутствующие ключи падают на русский.
 */
type ExtraModule = Record<Lang, Dict>

export const EXTRA_MODULES: ExtraModule[] = [
  REAL_DICTS,
  SHELL_DICTS,
  HISTORY_DICTS,
  MAP_DICTS,
  DATA_DICTS,
  AGENT_DICTS,
  DEMO_DICTS,
]

export const DICTS: Record<Lang, Dict> = Object.fromEntries(
  (Object.keys(BASE_DICTS) as Lang[]).map((l) => [
    l,
    Object.assign({}, BASE_DICTS[l], ...EXTRA_MODULES.map((m) => m[l] ?? {})),
  ]),
) as Record<Lang, Dict>

/** Перевод строки с подстановкой переменных {name}. */
export function tr(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? RU
  let s = dict[key] ?? RU[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  }
  return s
}
