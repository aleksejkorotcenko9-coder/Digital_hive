/**
 * Сезонная сборка демо-ульев: зимой показываем клуб (зимний покой),
 * осенью — снижение взятка; в основной сезон — летний канон.
 * Главная страница всегда соответствует реальному календарю.
 */
function buildSeasonalHives(date: Date): DemoHive[] {
  const phase = seasonPhase(date)
  if (phase === 'main_flow') return SUMMER_HIVES

  if (phase === 'winter_rest') {
    return SUMMER_HIVES.map((h) => {
      const wm = WINTER_META[h.scenario]
      return {
        ...h,
        scenarioLabel: wm.scenarioLabel,
        shortLabel: wm.shortLabel,
        roleLabel: wm.roleLabel,
        scenarioHint: wm.scenarioHint,
        index: wm.index,
        base: { ...h.base, ...WINTER_TELEMETRY[h.scenario] },
        prescriptions: WINTER_PRESCRIPTIONS[h.scenario],
      }
    })
  }

  // Промежуточные фазы: летний канон с поправкой на слабый/отсутствующий взяток.
  const autumn = phase === 'autumn_prep'
  const spring = phase === 'flight_start' || phase === 'buildup'
  if (!autumn && !spring) return SUMMER_HIVES
  return SUMMER_HIVES.map((h) => {
    const b = { ...h.base }
    if (autumn) {
      b.dailyGainKg = Math.min(b.dailyGainKg, 0.03)
      b.trafficPerMin = Math.round(b.trafficPerMin * 0.4)
      b.entranceLevel = b.entranceLevel === 'busy' ? 'ok' : b.entranceLevel
      b.entranceLabel = h.scenario === 'flow' ? 'Лёт умеренный — взяток закончился' : b.entranceLabel
      b.seasonGainKg = Math.round(b.seasonGainKg * 1)
    }
    if (spring) {
      b.dailyGainKg = Math.min(b.dailyGainKg, 0.08)
      b.trafficPerMin = Math.round(b.trafficPerMin * 0.6)
      b.entranceLevel = b.entranceLevel === 'busy' ? 'ok' : b.entranceLevel
    }
    return { ...h, base: b }
  })
}

