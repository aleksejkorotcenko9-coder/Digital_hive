/** Детерминированный генератор псевдослучайных чисел (mulberry32). */
function seeded(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Температура и влажность за 14 дней: колебания вокруг базовых значений. */
export function demoClimateSeries(h: DemoHive, days = 14): DayPoint[] {
  const rnd = seeded(1000 + h.id * 97)
  const out: DayPoint[] = []
  const nowMs = Date.now()
  for (let k = days - 1; k >= 0; k--) {
    const t = new Date(nowMs - k * 86400000)
    const recent = k <= 1
    const tempC = recent
      ? h.base.tempC + (rnd() - 0.5) * 0.2
      : h.base.tempC - 0.4 + rnd() * 0.8
    const humidityPct = recent
      ? h.base.humidityPct + (rnd() - 0.5) * 2
      : h.base.humidityPct - 4 + rnd() * 8
    out.push({
      date: format(t, 'yyyy-MM-dd'),
      label: format(t, 'd.MM'),
      full: format(t, 'd MMMM', { locale: ru }),
      weightKg: null,
      tempInC: Math.round(tempC * 10) / 10,
      humidityPct: Math.round(humidityPct),
    })
  }
  // последние две точки точно соответствуют «сейчас»
  out[out.length - 1].tempInC = h.base.tempC
  out[out.length - 1].humidityPct = h.base.humidityPct
  return out
}

