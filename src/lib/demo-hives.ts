/**
 * Статус заклещенности: Норма <2 % / Риск 2–3 % / Критично >3 %.
 * label — русский фолбэк из данных; key — ссылка на базовый словарь i18n
 * (dash.varroa.status.* уже переведены на все языки в i18n.ts).
 */
export function varroaStatus(pct: number): { level: 'ok' | 'risk' | 'crit'; key: string; label: string; cls: string } {
  if (pct > 3) return { level: 'crit', key: 'dash.varroa.status.crit', label: 'Критично', cls: 'bg-red-50 text-red-700 border-red-200' }
  if (pct >= 2) return { level: 'risk', key: 'dash.varroa.status.risk', label: 'Риск', cls: 'bg-amber-50 text-amber-700 border-amber-200' }
  return { level: 'ok', key: 'dash.varroa.status.ok', label: 'Норма', cls: 'bg-emerald-50 text-emerald-700 border-emerald-200' }
}

/** Состояние воздуха по индексу ЛОС (0…100). key → demo.voc.* в словаре DEMO_DICTS. */
export function vocState(v: number): { key: string; label: string; cls: string } {
  if (v > 60) return { key: 'demo.voc.hot', label: 'Духота — семье не хватает объема', cls: 'text-red-600' }
  if (v > 30) return { key: 'demo.voc.mid', label: 'Умеренная загрузка воздухом', cls: 'text-amber-600' }
  return { key: 'demo.voc.ok', label: 'Воздух чистый', cls: 'text-emerald-600' }
}

/** Состояние трафика на летке относительно нормы пасеки (45 пч/мин). key → demo.traffic.* в словаре DEMO_DICTS. */
export function trafficState(v: number): { key: string; label: string; cls: string } {
  if (v >= 55) return { key: 'demo.traffic.high', label: 'Интенсивный лёт', cls: 'text-emerald-600' }
  if (v >= 30) return { key: 'demo.traffic.active', label: 'Активный лёт', cls: 'text-emerald-600' }
  if (v >= 18) return { key: 'demo.traffic.weak', label: 'Лёт ослаблен', cls: 'text-amber-600' }
  return { key: 'demo.traffic.low', label: 'Лёт резко снижен', cls: 'text-red-600' }
}

/** Индекс 0…10 → подпись и тон шкалы. */
export function demoGaugeInfo(value: number): { label: string; tone: 'ok' | 'normal' | 'watch' | 'alert' } {
  if (value < 4) return { label: 'Тревожное состояние', tone: 'alert' }
  if (value < 6) return { label: 'Требует внимания', tone: 'watch' }
  if (value < 8.5) return { label: 'Нормальное состояние', tone: 'normal' }
  return { label: 'Отличное состояние', tone: 'ok' }
}

