export interface VarroaPoint {
  label: string
  /** Историческое значение заклещенности, %. */
  pct: number | null
  /** Пунктирный сегмент прогноза: последнее значение → прогноз +14 дней. */
  forecast: number | null
  /** Отметка проведенной обработки. */
  treated: boolean
}

/**
 * Динамика заклещенности за 30 дней + прогноз на 14 дней вперед.
 * Ульи №1 и №2 обработаны щавелевой кислотой 12 дней назад (виден дип),
 * №3 — лечения не было, показатель растет, №4 — обработка 20 дней назад.
 *
 * opts.overridePct — «текущее» значение после проведения обработки или нового
 * замера (кривая сходится к нему); opts.treatedToday — сегодня была обработка:
 * на последней точке рисуется дип, а прогноз считается от нового значения.
 */
export function demoVarroaSeries(
  h: DemoHive,
  days = 30,
  opts?: { overridePct?: number; treatedToday?: boolean },
): VarroaPoint[] {
  const rnd = seeded(3000 + h.id * 57)
  const out: VarroaPoint[] = []
  const nowMs = Date.now()

  const curPct = opts?.overridePct ?? h.base.varroaPct
  const treatedToday = opts?.treatedToday ?? false
  // прогноз: после обработки семья восстанавливается (+0,1 за 14 дн),
  // без обработки критический улей продолжает расти (+1,6)
  const futurePct =
    opts?.overridePct !== undefined || treatedToday
      ? Math.round((curPct + (treatedToday ? 0.1 : 0.2)) * 10) / 10
      : h.base.varroaForecast14d

  // траектория «назад»: стартовая точка → текущая, с дипом после обработки
  const treatDay = h.scenario === 'norm' || h.scenario === 'flow' ? 12 : h.scenario === 'swarm' ? 20 : -1
  const startPct = h.scenario === 'varroa' ? 1.2 : h.scenario === 'swarm' ? 2.6 : 1.4

  for (let k = days - 1; k >= 0; k--) {
    const t = new Date(nowMs - k * 86400000)
    const progress = 1 - k / (days - 1) // 0 → 1 к «сегодня»
    let pct = startPct + (curPct - startPct) * progress
    // дип после обработки: −1,2 % в течение 3 дней
    if (treatDay > 0 && k <= treatDay && k > treatDay - 4) {
      pct -= 1.2 * ((treatDay - k + 1) / 4)
    }
    pct += (rnd() - 0.5) * 0.12
    out.push({
      label: format(t, 'd.MM'),
      pct: Math.max(0.2, Math.round(pct * 10) / 10),
      forecast: null,
      treated: treatDay > 0 && k === treatDay,
    })
  }
  out[out.length - 1].pct = curPct

  // свежая обработка: дип на последней точке (кривая резко падает)
  if (treatedToday && out.length >= 2) {
    out[out.length - 2].treated = true
  }

  // прогноз: через 14 дней (пунктир от текущей точки)
  const future = new Date(nowMs + 14 * 86400000)
  out.push({
    label: format(future, 'd.MM'),
    pct: null,
    forecast: futurePct,
    treated: false,
  })
  // сегмент начинается с последней исторической точки
  out[out.length - 2].forecast = curPct
  return out
}

/**
 * Привесы за 7 дней: столбцы суточного привеса + ночная температура
 * (ночные похолодания объясняют провалы приноса нектара).
 */
export function demoGainSeries(h: DemoHive, days = 7): Array<{ label: string; gainKg: number; nightTempC: number }> {
  const rnd = seeded(4000 + h.id * 83)
  const out: Array<{ label: string; gainKg: number; nightTempC: number }> = []
  const nowMs = Date.now()
  // Сезонная база ночной температуры (средняя полоса) и нижний предел привеса.
  const phase = seasonPhase(new Date())
  const nightBase = phase === 'winter_rest' ? -7 : phase === 'flight_start' ? 3 : phase === 'buildup' ? 9 : phase === 'autumn_prep' ? 7 : 14
  const gainFloor = phase === 'winter_rest' ? -0.35 : phase === 'autumn_prep' ? -0.15 : -0.1
  for (let k = days - 1; k >= 0; k--) {
    const t = new Date(nowMs - k * 86400000)
    // привес качается вокруг базового: погода и сила семьи
    const gainKg = k === 0 ? h.base.dailyGainKg : Math.max(gainFloor, h.base.dailyGainKg + (rnd() - 0.45) * 0.5)
    // ночная температура: волна + случайные похолодания (2 прохладные ночи)
    const wave = Math.sin(((days - k) / days) * Math.PI * 1.4) * 3
    const dip = k === days - 2 || k === 1 ? -3.5 : 0
    const nightTempC = nightBase + wave + dip + (rnd() - 0.5) * 2
    out.push({
      label: format(t, 'd.MM'),
      gainKg: Math.round(gainKg * 100) / 100,
      nightTempC: Math.round(nightTempC * 10) / 10,
    })
  }
  return out
}

