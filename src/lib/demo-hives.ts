/**
 * Строка вечернего отчета: icon — для иконки, key — стабильный идентификатор
 * для i18n-ключей demo.evening.<key>.title / .text, title/text — русский
 * канонический текст (фолбэк, собранный из живых чисел), vars — подстановки.
 */
export interface EveningLine {
  icon: 'weight' | 'varroa' | 'bloom' | 'hive' | 'weather'
  key: string
  title: string
  text: string
  vars?: Record<string, string | number>
}

/**
 * Суточная сводка для пчеловода: чистый привес нектара, статус заклещенности
 * и прогноз цветения по GDD. Собирается из текущих живых значений.
 *
 * lang — язык перевода шаблонов demo.evening.* (по умолчанию русский);
 * локализованные слова статуса берутся из базового словаря dash.varroa.status.*,
 * названия медоносов — из demo.crop.*. Возвращаемый title/text остаются
 * русскими фолбэками для tf() в EveningReportDialog.
 */
export function eveningReportLines(
  hives: DemoHive[],
  liveById: Record<number, LiveDemoValues | undefined>,
  doneList: Record<number, string[]>,
  lang: Lang = 'ru',
): EveningLine[] {
  void liveById
  const loc = (key: string, vars?: Record<string, string | number>) => tr(lang, key, vars)
  const lines: EveningLine[] = []

  const gainTotal = hives.reduce((s, h) => s + h.base.dailyGainKg, 0)
  const weightVars = {
    gain: fmtSigned(gainTotal, 2),
    bestHive: hives[1].id,
    best: fmtSigned(hives[1].base.dailyGainKg, 2),
    hz: hives[1].base.soundHz,
  }
  lines.push({
    icon: 'weight',
    key: 'weight',
    title: loc('demo.evening.weight.title'),
    text: loc('demo.evening.weight.text', weightVars),
    vars: weightVars,
  })

  // локализованные слова статуса заклещенности из базового словаря (со строчной — как в оригинале)
  const statusWord = (level: string) => loc(`dash.varroa.status.${level}`).toLowerCase()
  const varroaItems = hives.map((h) => {
    const st = varroaStatus(h.base.varroaPct)
    return h.scenario === 'varroa'
      ? loc('demo.evening.varroa.itemF', {
          n: h.id,
          p: fmtNum(h.base.varroaPct),
          s: statusWord(st.level),
          f: fmtNum(h.base.varroaForecast14d),
        })
      : loc('demo.evening.varroa.item', {
          n: h.id,
          p: fmtNum(h.base.varroaPct),
          s: statusWord(st.level),
        })
  })
  const varroaVars = { list: varroaItems.join('; '), f3: fmtNum(hives[2].base.varroaForecast14d) }
  lines.push({
    icon: 'varroa',
    key: 'varroa',
    title: loc('demo.evening.varroa.title'),
    text: loc('demo.evening.varroa.text', varroaVars),
    vars: varroaVars,
  })

  const bloom = nearestBloom()
  if (bloom.paused) {
    lines.push({
      icon: 'bloom',
      key: 'bloomPaused',
      title: loc('demo.evening.bloomPaused.title'),
      text: loc('demo.evening.bloomPaused.text'),
    })
  } else {
    const bloomVars = {
      name: loc(`demo.crop.${bloom.key}`),
      cur: GDD_CURRENT,
      need: GDD_CROPS[0].need,
      d: bloom.daysLeft,
      pct: bloom.pct,
    }
    lines.push({
      icon: 'bloom',
      key: 'bloom',
      title: loc('demo.evening.bloom.title'),
      text: loc('demo.evening.bloom.text', bloomVars),
      vars: bloomVars,
    })
  }

  lines.push({
    icon: 'weather',
    key: 'weather',
    title: loc('demo.evening.weather.title'),
    text: loc('demo.evening.weather.text'),
  })

  const done = hives.reduce((s, h) => s + (doneList[h.id]?.length ?? 0), 0)
  if (done > 0) {
    const doneVars = { n: done }
    lines.push({
      icon: 'hive',
      key: 'done',
      title: loc('demo.evening.done.title'),
      text: loc('demo.evening.done.text', doneVars),
      vars: doneVars,
    })
  } else {
    lines.push({
      icon: 'hive',
      key: 'doneNone',
      title: loc('demo.evening.doneNone.title'),
      text: loc('demo.evening.doneNone.text'),
    })
  }

  return lines
}
