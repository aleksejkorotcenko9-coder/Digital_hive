/** Нормализация кода: верхний регистр, без пробелов и дефисов — «sn 2518 0147» найдётся. */
export function normalizeCode(raw: string): string {
  return raw.toUpperCase().replace(/[\s–—-]+/g, '')
}

/** Поиск датчика по коду с корпуса (регистр, пробелы и дефисы не важны). */
export function findSensor(raw: string): SensorDevice | null {
  const code = normalizeCode(raw)
  if (!code) return null
  return SENSOR_CATALOG.find((s) => normalizeCode(s.code) === code) ?? null
}
